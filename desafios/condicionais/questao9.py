# Crie o verificador de final de semana e de dia da semana (switch)

dia_atual = input('Qual é o dia da semana? ')

if dia_atual.lower() == 'segunda':
    print('Dia de Senama')
elif dia_atual.lower() == 'terça':
    print('Dia de Senama')
elif dia_atual.lower() == 'Quarta':
    print('Dia de Senama')
elif dia_atual.lower() == 'quinta':
    print('Dia de Senama')
elif dia_atual.lower() == 'sexta':
    print('Dia de Senama')
elif dia_atual.lower() == 'sábado' or 'sabado':
    print('Final de Semana')
elif dia_atual.lower() == 'domingo':
    print('Final de Semana')
